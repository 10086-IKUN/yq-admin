create table if not exists text_to_sql_eval_question (
    id bigint primary key auto_increment comment '主键ID',
    question text not null comment '评测问题',
    business_id varchar(64) null comment '业务标识',
    business_name varchar(128) null comment '业务名称',
    eval_target varchar(64) not null default 'END_TO_END' comment '评测目标：ROUTING/BUSINESS_SKILL/METRIC_RETRIEVAL/TABLE_SCHEMA_RETRIEVAL/SQL_GENERATION/CLARIFICATION/RESULT_ANALYSIS/END_TO_END',
    sample_category varchar(64) not null default 'NORMAL' comment '样本场景：NORMAL/BOUNDARY/REGRESSION/AMBIGUOUS/NEGATIVE',
    source_type varchar(32) not null comment '来源：MANUAL/RUN_HISTORY/FEEDBACK',
    source_run_id bigint null comment '来源运行记录ID',
    source_conversation_id varchar(64) null comment '来源会话ID',
    generated_sql text null comment '来源运行生成SQL',
    executed_sql text null comment '来源运行执行SQL',
    final_answer text null comment '来源运行最终回答',
    feedback_result varchar(32) null comment '来源反馈结果：CORRECT/INCORRECT',
    feedback_error_type varchar(64) null comment '来源反馈错误类型',
    feedback_comment text null comment '来源反馈说明',
    judge_note text null comment '人工判断说明',
    remark text null comment '整理备注',
    status varchar(32) not null default 'DRAFT' comment 'DRAFT/ACTIVE/DISABLED',
    created_by bigint null comment '创建人ID',
    created_at datetime not null default current_timestamp comment '创建时间',
    updated_at datetime not null default current_timestamp on update current_timestamp comment '更新时间',
    unique key uk_text_to_sql_eval_question_source_run_id (source_run_id),
    key idx_text_to_sql_eval_question_status (status),
    key idx_text_to_sql_eval_question_business_id (business_id),
    key idx_text_to_sql_eval_question_eval_target (eval_target),
    key idx_text_to_sql_eval_question_sample_category (sample_category),
    key idx_text_to_sql_eval_question_source_type (source_type),
    key idx_text_to_sql_eval_question_created_at (created_at)
) comment 'Text-to-SQL 评测样本';

